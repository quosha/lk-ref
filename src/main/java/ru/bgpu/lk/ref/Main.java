
package ru.bgpu.lk.ref;

/**
 * Главный класс приложения, демонстрирующий использование Reflection API
 * для конфигурации приложения через аннотации.
 * 
 * В статическом блоке происходит инициализация полей с аннотацией @AppConfig
 * перед выполнением основного метода программы. Это гарантирует, что
 * конфигурационные значения будут загружены до создания экземпляров классов.
 */
public class Main {
    
    /**
     * Статический блок инициализации, который выполняется при загрузке класса.
     * 
     * Вызывает метод AppConfigWorker.init для сканирования пакета "ru.bgpu.lk.ref"
     * и инициализации всех полей с аннотацией @AppConfig значениями из файла
     * "config.properties".
     * 
     * Это демонстрирует один из практических сценариев использования Reflection API:
     * автоматическая конфигурация приложения на основе аннотаций.
     */
    static {
        AppConfigWorker.init("ru.bgpu.lk.ref", "config.properties");
    }
    
    /**
     * Основной метод приложения, демонстрирующий результат работы Reflection API.
     * 
     * Создаются экземпляры класса A, поля которых (name и host) уже были
     * проинициализированы через Reflection API в статическом блоке.
     * 
     * При выводе объектов на экран видно, что поля содержат значения из
     * конфигурационного файла, что подтверждает успешную работу механизма
     * конфигурации через аннотации.
     * 
     * @param args аргументы командной строки (не используются)
     */
    public static void main(String[] args) {
        // Создание первого экземпляра класса A
        A a = new A();
        System.out.println("a = " + a);
        
        // Создание второго экземпляра для демонстрации, что поля статические
        // и общие для всех экземпляров
        System.out.println("new A = " + new A());
    }
}
