
package ru.bgpu.lk.ref;

/**
 * Класс A демонстрирует использование аннотации @AppConfig для конфигурации полей.
 * 
 * Этот класс содержит статические поля, значения которых загружаются из
 * конфигурационного файла с помощью Reflection API через класс AppConfigWorker.
 * 
 * При инициализации (в статическом блоке класса Main) поля name и host
 * получают значения из файла config.properties, а если значения отсутствуют,
 * используются значения по умолчанию, указанные в аннотациях.
 */
public class A {
    
    /**
     * Приватное статическое поле name с аннотацией @AppConfig.
     * Значение по умолчанию "hi!" будет использоваться, если в конфигурационном
     * файле отсутствует свойство с именем "name".
     * 
     * Аннотация @AppConfig позволяет Reflection API обнаружить это поле
     * и установить его значение из внешнего источника конфигурации.
     */
    @AppConfig(value = "hi!")
    private static String name;
    
    /**
     * Статическое поле host с аннотацией @AppConfig без указания значения по умолчанию.
     * Если в конфигурационном файле отсутствует свойство "host", будет использована
     * пустая строка (значение по умолчанию аннотации).
     */
    @AppConfig
    static String host;
    
    /**
     * Метод test помечен аннотацией @Deprecated для демонстрации,
     * что Reflection API может также обнаруживать другие аннотации.
     * 
     * @deprecated Этот метод устарел и не должен использоваться.
     */
    @Deprecated
    void test() {
        // Пустая реализация для демонстрации аннотации @Deprecated
    }

    /**
     * Переопределенный метод toString, который возвращает строковое представление
     * объекта вместе с текущими значениями полей name и host.
     * 
     * Поля name и host инициализируются через Reflection API до создания
     * экземпляров класса, поэтому их значения доступны при вызове toString().
     * 
     * @return строковое представление объекта с значениями полей конфигурации
     */
    @Override
    public String toString() {
        return super.toString() + " {name = " + name + ", host = " + host + "}";
    }
    
}
